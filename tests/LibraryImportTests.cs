using System;
using System.Collections.Generic;
using System.IO;
using System.Threading;
using System.Threading.Tasks;
using ThorCapture.Backend;

namespace ThorCapture
{
    internal static class LibraryImportTests
    {
        internal static void Run() { Task.Run(() => Workflow()).GetAwaiter().GetResult(); }
        private static async Task WaitFor(CocoonBackend backend, BackendState state)
        {
            DateTime deadline = DateTime.UtcNow.AddSeconds(15);
            while (backend.State != state && DateTime.UtcNow < deadline) await Task.Delay(20);
            if (backend.State != state) throw new Exception("Backend did not reach " + state);
        }
        private static async Task Workflow()
        {
            string backendDir = Path.GetFullPath(Path.Combine(Adb.AppDir(), "../../cocoon-art-backend"));
            string makerScript = Path.GetFullPath(Path.Combine(Adb.AppDir(), "../tools/cocoon-demo.cjs"));
            if (!File.Exists(Path.Combine(backendDir, "backend.cjs")) || !File.Exists(makerScript))
                throw new Exception("Library import integration requires the Cocoon backend and existing demo fixture");
            string source = Path.Combine(Tests.Root, "import 来源 " + Guid.NewGuid().ToString("N"));
            string target = Path.Combine(Tests.Root, "import target " + Guid.NewGuid().ToString("N"));
            using (ProcessRunner maker = new ProcessRunner())
            {
                ProcessResult result = await maker.RunAsync(new ProcessRequest("node", "fixture.library", new[] { makerScript, source }), TimeSpan.FromSeconds(30), CancellationToken.None);
                Tests.Check(result.Outcome == ProcessOutcome.Success && result.CleanupComplete, "library import fixture is generated by an owned child with safe path arguments");
                await maker.StopAllAsync();
            }
            string sourceDb = Path.Combine(source, "_data/cocoon_db"); byte[] before = File.ReadAllBytes(sourceDb);
            CocoonBackend backend = new CocoonBackend(null) { BackendDir = backendDir, DataRoot = target };
            try
            {
                backend.Start(); await WaitFor(backend, BackendState.Ready);
                Tests.Check(((List<object>)backend.GetJson("/api/games")).Count == 0, "native backend sees missing library as an empty list");
                LibraryImportClient client = new LibraryImportClient(backend);
                LibraryImportPlan plan = await client.PlanAsync(source);
                Tests.Check(plan.TotalGames == 24 && plan.VisibleGames == 24 && plan.Files.Length > 1 && plan.TotalBytes > 0 && !plan.ReplacesExistingLibrary,
                    "native import plan exposes counts and reviewable files from the real authenticated endpoint");
                bool rejected = false;
                try { await client.ExecuteAsync(plan.PlanId, false); }
                catch (BackendRequestException failure) { rejected = failure.Code == "IMPORT_CONFIRM_REQUIRED" && failure.Status == 400 && !failure.Message.Contains(source); }
                Tests.Check(rejected, "native import errors retain code and status without private source paths");
                LibraryImportJob job = await client.ExecuteAsync(plan.PlanId, true);
                DateTime deadline = DateTime.UtcNow.AddSeconds(15);
                while (!job.Finished && DateTime.UtcNow < deadline) { await Task.Delay(20); job = await client.StatusAsync(job.JobId); }
                Tests.Check(job.State == "completed" && job.CanRestore && job.CopiedFiles == job.TotalFiles,
                    "native import client polls one asynchronous job through verified completion");
                Tests.Check(((List<object>)backend.GetJson("/api/games")).Count == 24 && backend.GetBytes("/api/art?id=1&type=icon") != null,
                    "native library and cached artwork become readable after import");
                Tests.Check(Convert.ToBase64String(before) == Convert.ToBase64String(File.ReadAllBytes(sourceDb)), "native import leaves the source database unchanged");
                bool endpointRejected = false;
                try { backend.PostJson("https://invalid.example/api/data", "{}"); }
                catch (BackendRequestException failure) { endpointRejected = failure.Code == "ENDPOINT_REJECTED"; }
                Tests.Check(endpointRejected, "authenticated POST cannot send its token outside the owned endpoint");
                endpointRejected = false;
                try { backend.GetJson("https://invalid.example/api/data"); }
                catch (BackendRequestException failure) { endpointRejected = failure.Code == "ENDPOINT_REJECTED"; }
                Tests.Check(endpointRejected, "authenticated GET cannot send its token outside the owned endpoint");
                bool typedReadError = false;
                try { await client.StatusAsync(Guid.NewGuid().ToString()); }
                catch (BackendRequestException failure) { typedReadError = failure.Code == "IMPORT_NOT_FOUND" && failure.Status == 404; }
                Tests.Check(typedReadError, "missing import job preserves the typed backend read error");
                await client.RestoreAsync(job.ImportId, true);
                Tests.Check(((List<object>)backend.GetJson("/api/games")).Count == 0 && (await client.StatusAsync(job.JobId)).State == "restored",
                    "native restore returns the prior empty library and retires its undo action");
            }
            finally { backend.Stop(); WaitFor(backend, BackendState.Stopped).GetAwaiter().GetResult(); }
            Tests.Check(backend.State == BackendState.Stopped, "native import integration exits only its owned backend process");
        }
    }
}
